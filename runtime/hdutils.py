def validate_singlets_properties(
    df: pd.DataFrame,
) -> pd.DataFrame:
    """Validate the conventions of a SingleTSFrame

    A SingleTSFrame holds a single — possibly multi-dimensional — timeseries. It has the same
    tabular representation as a MultiTSFrame, except that it has no "metric" column, since
    the metric is unique for the whole frame. Every column besides "timestamp" is a value
    dimension. This explicitly includes a column named "metric", which is treated like any
    other value column here.
    """
    if len(df.columns) == 0:
        attrs = df.attrs
        df = pd.DataFrame(columns=SINGLETSFRAME_COLUMN_NAMES)
        df.attrs = attrs

    if len(df.columns) < 2:
        raise ValueError(
            "SingleTSFrame requires at least 2 columns: timestamp"
            f" and at least one value column. Only found {str(df.columns)}"
        )

    if "timestamp" not in df.columns:
        column_names_string = ", ".join(df.columns)
        raise ValueError(
            f"The column names {column_names_string} don't contain the required column"
            ' "timestamp" for a SingleTSFrame.'
        )

    if df["timestamp"].isna().any():
        raise ValueError(
            "No null values are allowed for the column 'timestamp' of a SingleTSFrame."
        )

    if len(df.index) == 0:
        df["timestamp"] = pd.to_datetime(df["timestamp"], utc=True)

    if not isinstance(df["timestamp"].dtype, pd.DatetimeTZDtype):
        raise ValueError(
            "Column 'timestamp' of SingleTSFrame does not have DatetimeTZDtype dtype. "
            f"Got {str(df['timestamp'].dtype)} index dtype instead."
        )

    if df["timestamp"].dt.tz not in (pytz.UTC, datetime.timezone.utc):
        raise ValueError(
            "Column 'timestamp' of SingleTSFrame does not have UTC timezone. "
            f"Got {str(df['timestamp'].dt.tz)} timezone instead."
        )

    return df.sort_values("timestamp")


